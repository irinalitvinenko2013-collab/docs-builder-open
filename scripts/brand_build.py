"""Запекание профиля: профили/<имя>/profile.json → рабочая тема документа.

Что делает:
  1. находит активный профиль (аргумент → файл профили/_активный → единственный профиль);
  2. пишет context/theme.css  — @font-face + :root с цветами профиля (его подключает skeleton);
  3. пишет context/автор.md   — канон-данные автора для вёрстки (дословно, ничего не выдумывать);
  4. копирует логотипы и фото профиля в assets/профиль/.

Запуск:
    .venv/bin/python scripts/brand_build.py            # активный профиль
    .venv/bin/python scripts/brand_build.py клиенту-ромашка
    .venv/bin/python scripts/brand_build.py --список
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROFILES = ROOT / "профили"
ACTIVE_FILE = PROFILES / "_активный"
CONTEXT = ROOT / "context"
ASSETS = ROOT / "assets" / "профиль"
FONTS = ROOT / "assets" / "fonts"

# Шрифты, которые ставит scripts/setup.sh. Свой файл шрифта тоже можно положить
# в assets/fonts/<Имя>.ttf — тогда он подхватится по имени из профиля.
KNOWN_FONTS = {
    "Montserrat": "Montserrat.ttf",
    "Open Sans": "OpenSans.ttf",
    "PT Sans": "PTSans.ttf",
    "Lora": "Lora.ttf",
    "Inter": "Inter.ttf",
    "Playfair Display": "PlayfairDisplay.ttf",
}

ROLES = [
    ("тёмный_фон_1", "--navy", "тёмный фон"),
    ("тёмный_фон_2", "--graphite", "тёмный фон, второй тон"),
    ("светлый_фон_1", "--warm-white", "светлый фон"),
    ("светлый_фон_2", "--cream", "светлый фон, второй тон"),
    ("акцент", "--burgundy", "главный акцент"),
    ("акцент_средний", "--red-mid", "акцент средний"),
    ("акцент_яркий", "--red", "акцент яркий"),
    ("акцент_второй", "--accent-2", "второй акцент — полоски, иконки, детали"),
    ("тёплый", "--gold", "цитаты, значки, рамки"),
    ("тёплый_мягкий", "--gold-soft", "тот же тон мягче"),
    ("текст", "--ink", "текст на светлом"),
    ("текст_мягкий", "--ink-soft", "вторичный текст"),
    ("линия", "--line", "разделители"),
]


def стоп(текст):
    """Остановиться по-человечески: ученик должен понять, что делать."""
    print("\n⛔ " + текст + "\n")
    sys.exit(1)


def список_профилей():
    if not PROFILES.exists():
        return []
    return sorted(
        p.name
        for p in PROFILES.iterdir()
        if p.is_dir() and not p.name.startswith("_") and (p / "profile.json").exists()
    )


def активный_профиль(аргумент=None):
    имена = список_профилей()
    # Служебные папки (начинаются с «_») в общий список не попадают, но запечь их явно
    # можно: самопроверке нужна тема ещё до того, как заведён первый профиль.
    if аргумент and аргумент.startswith("_") and (PROFILES / аргумент / "profile.json").exists():
        return аргумент
    if аргумент:
        if аргумент not in имена:
            стоп(
                f"Профиля «{аргумент}» нет. Сейчас заведены: {', '.join(имена) or '— ни одного'}.\n"
                "   Скажите системе «настрой профиль» — она заведёт новый и всё спросит сама."
            )
        return аргумент
    if ACTIVE_FILE.exists():
        имя = ACTIVE_FILE.read_text(encoding="utf-8").strip()
        if имя in имена:
            return имя
    if len(имена) == 1:
        return имена[0]
    if not имена:
        стоп(
            "Ни одного профиля ещё нет — система не знает, чей это документ.\n"
            "   Скажите ей «настрой профиль»: спросит имя, цвета, контакты и заведёт папку."
        )
    стоп(
        "Профилей несколько, а активный не выбран: " + ", ".join(имена) + ".\n"
        "   Скажите словами, в каком работаем, — или впишите имя в файл профили/_активный."
    )


def прочитать(имя):
    файл = PROFILES / имя / "profile.json"
    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        стоп(
            f"Файл {файл} повреждён (ошибка на строке {e.lineno}).\n"
            "   Чаще всего это лишняя или пропущенная запятая. Скажите системе «почини профиль» —\n"
            "   она покажет это место. Рядом всегда лежит образец: профили/_шаблон/profile.json"
        )
    шаблон = json.loads((PROFILES / "_шаблон" / "profile.json").read_text(encoding="utf-8"))
    # недостающие поля добираем из шаблона — профиль не обязан быть заполнен целиком
    for ключ, значение in шаблон.items():
        данные.setdefault(ключ, значение)
    # «акцент_второй» появился позже остальных ролей: у профилей, заведённых раньше,
    # его нет — берём их же яркий акцент, чтобы вид документов не менялся сам собой
    данные["палитра"].setdefault(
        "акцент_второй",
        данные["палитра"].get("акцент_яркий", шаблон["палитра"]["акцент_второй"]),
    )
    for ключ, значение in шаблон["палитра"].items():
        данные["палитра"].setdefault(ключ, значение)
    for ключ, значение in шаблон["шрифты"].items():
        данные["шрифты"].setdefault(ключ, значение)
    return данные


def файл_шрифта(название):
    имя = KNOWN_FONTS.get(название, название.replace(" ", "") + ".ttf")
    путь = FONTS / имя
    if путь.exists():
        return имя, None
    запасной = "Montserrat.ttf" if (FONTS / "Montserrat.ttf").exists() else None
    предупреждение = (
        f"шрифт «{название}» не найден в assets/fonts/ — "
        + ("взяла запасной" if запасной else "рендер пойдёт системным шрифтом")
    )
    return (запасной or имя), предупреждение


def в_rgb(hex_цвет):
    """#0D1B2A → «13,27,42» — для полупрозрачных фонов вида rgba(var(--navy-rgb),.4)."""
    h = hex_цвет.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    try:
        return ",".join(str(int(h[i : i + 2], 16)) for i in (0, 2, 4))
    except ValueError:
        return "0,0,0"


def _каналы(hex_цвет):
    h = hex_цвет.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    try:
        return [int(h[i : i + 2], 16) for i in (0, 2, 4)]
    except ValueError:
        return [0, 0, 0]


def смешать(цвет, с_чем, доля):
    """Смешать два цвета: доля 0 — первый, 1 — второй."""
    a, b = _каналы(цвет), _каналы(с_чем)
    return "#" + "".join(f"{round(x + (y - x) * доля):02X}" for x, y in zip(a, b))


def контрастный(цвет, светлый, тёмный):
    """Что читаемо поверх этого цвета — светлый текст или тёмный."""
    r, g, b = _каналы(цвет)
    яркость = (0.299 * r + 0.587 * g + 0.114 * b) / 255
    return тёмный if яркость > 0.6 else светлый


def производные(палитра):
    """Роли, которых человек не называет, но вёрстке они нужны каждый раз.

    Без них шаблоны подставляли #fff, #3A0E14 и прочие константы — и документ
    переставал переезжать в другой профиль, хотя это главное свойство системы.
    Считаем их из палитры, чтобы они ехали за профилем сами.
    """
    светлый = палитра["светлый_фон_1"]
    тёплый = палитра["тёплый"]
    return [
        # карточка поверх светлой страницы — чуть светлее самого фона
        ("--card", смешать(светлый, "#FFFFFF", 0.75), "фон карточки на светлой странице"),
        ("--card-warm", смешать(палитра["тёплый_мягкий"], "#FFFFFF", 0.82), "тёплая подложка врезки"),
        ("--on-accent", контрастный(палитра["акцент"], "#FFFFFF", палитра["текст"]), "текст поверх акцента"),
        ("--on-warm", контрастный(тёплый, "#FFFFFF", палитра["текст"]), "текст поверх тёплого"),
        ("--gold-deep", смешать(тёплый, палитра["текст"], 0.25), "тёплый глубже — для градиента"),
    ]


def собрать_тему(профиль):
    предупреждения = []
    заголовки = профиль["шрифты"]["заголовки"]
    текст = профиль["шрифты"]["текст"]
    файл_загл, п1 = файл_шрифта(заголовки)
    файл_текст, п2 = файл_шрифта(текст)
    предупреждения += [п for п in (п1, п2) if п]

    строки = [
        "/* Тема документа. ФАЙЛ СОБИРАЕТСЯ АВТОМАТИЧЕСКИ — правьте профиль, а не его. */",
        f"/* Профиль: {профиль['профиль']} — {профиль.get('название', '')} */",
        "",
        # Путь считается ОТ ЭТОГО ФАЙЛА (он лежит в context/), а не от корня —
        # иначе браузер ищет шрифт в context/assets/ и молча печатает системным.
        f"@font-face{{font-family:'{заголовки}';src:url('../assets/fonts/{файл_загл}');font-weight:100 900;}}",
        f"@font-face{{font-family:'{текст}';src:url('../assets/fonts/{файл_текст}');font-weight:300 800;}}",
        "",
        ":root{",
        f"  --font-heading:'{заголовки}',sans-serif;",
        f"  --font-body:'{текст}',sans-serif;",
    ]
    for ключ, переменная, подпись in ROLES:
        строки.append(f"  {переменная}:{профиль['палитра'][ключ]};".ljust(34) + f"/* {подпись} */")
    строки.append("")
    for переменная, значение, подпись in производные(профиль["палитра"]):
        строки.append(f"  {переменная}:{значение};".ljust(34) + f"/* {подпись} — считается сам */")
    # те же цвета в виде «R,G,B» — нужны там, где вёрстка делает полупрозрачность
    строки.append("")
    for ключ, переменная, _ in ROLES:
        строки.append(f"  {переменная}-rgb:{в_rgb(профиль['палитра'][ключ])};")
    строки += ["}", ""]

    CONTEXT.mkdir(exist_ok=True)
    (CONTEXT / "theme.css").write_text("\n".join(строки), encoding="utf-8")
    return предупреждения


def разобрать_контакт(к):
    """Контакт из профиля → (название, адрес, кликабельная ссылка).

    Поля читаются гибко: человек (или нейросеть, заполняющая профиль) пишет то
    «название/адрес», то «что/значение» — форма не должна решать, попадёт контакт
    в документ или нет. Раньше несовпадение имён давало пустую строку молча, и в
    готовой памятке оставалось «просто напишите» без единого адреса.

    Ссылку достраиваем сами: почта → mailto:, @имя → телеграм, домен → https://.
    """
    название = (к.get("название") or к.get("что") or к.get("тип") or "").strip()
    адрес = str(к.get("адрес") or к.get("значение") or к.get("контакт") or "").strip()
    ссылка = (к.get("url") or "").strip()
    if адрес and not ссылка:
        if адрес.startswith(("http://", "https://", "mailto:")):
            ссылка = адрес
        elif адрес.startswith("@"):
            ссылка = "https://t.me/" + адрес.lstrip("@")
        elif "@" in адрес and "." in адрес.split("@")[-1]:
            ссылка = "mailto:" + адрес
        elif адрес.startswith("+") and sum(с.isdigit() for с in адрес) >= 7:
            ссылка = "tel:" + "".join(с for с in адрес if с.isdigit() or с == "+")
        elif "." in адрес and " " not in адрес:
            ссылка = "https://" + адрес.lstrip("/")
    return название or "Контакт", адрес, ссылка


def собрать_автора(профиль):
    предупреждения = []
    а = профиль["автор"]
    строки = [
        "# Данные автора — единственный источник правды",
        "",
        "> Файл собирается автоматически из профиля. Всё, что попадает на страницу «Об авторе»,",
        "> берётся ТОЛЬКО отсюда и дословно. Нет факта здесь — не выдумывать, блок сделать короче.",
        f"> Профиль: `{профиль['профиль']}` — {профиль.get('название', '')}",
        "",
        f"- **Имя:** {а.get('имя') or '— не заполнено'}",
        f"- **Роль:** {а.get('роль') or '— не заполнено'}",
    ]
    if а.get("био"):
        строки += ["", "## Био", "", а["био"]]
    if а.get("метрики"):
        строки += ["", "## Цифры (дословно)", "", "| Число | Подпись | Уточнение |", "|---|---|---|"]
        for м in а["метрики"]:
            строки.append(
                f"| {м.get('число', '')} | {м.get('подпись', '')} | {м.get('уточнение', '—')} |"
            )
    if а.get("достижения"):
        строки += ["", "## Достижения (дословно)", ""]
        for i, д in enumerate(а["достижения"], 1):
            if isinstance(д, str):
                д = {"заголовок": д}
            тег = f" · тег `{д['тег']}`" if д.get("тег") else ""
            описание = д.get("описание", "")
            хвост = f" — {описание}" if описание else ""
            строки.append(f"{i}. **{д.get('заголовок', '')}**{тег}{хвост}")
    if профиль.get("контакты"):
        строки += ["", "## Контакты (всегда кликабельные)", ""]
        for к in профиль["контакты"]:
            название, адрес, ссылка = разобрать_контакт(к)
            if not адрес:
                предупреждения.append(
                    f"контакт {к} не понят — в документе его не будет. "
                    "Нужны поля «название» и «адрес» (см. профили/_шаблон/profile.json)"
                )
                continue
            строки.append(f"- {название}: {адрес} → {ссылка}")
    if а.get("цитаты"):
        строки += ["", "## Цитаты автора (можно ставить акцент-блоком)", ""]
        строки += [f"- «{ц}»" for ц in а["цитаты"]]
    if профиль.get("подпись_в_подвале"):
        строки += ["", "## Подпись в подвале страниц", "", профиль["подпись_в_подвале"]]

    CONTEXT.mkdir(exist_ok=True)
    (CONTEXT / "автор.md").write_text("\n".join(строки) + "\n", encoding="utf-8")
    return предупреждения


def скопировать_активы(имя, профиль):
    предупреждения = []
    ASSETS.mkdir(parents=True, exist_ok=True)
    for старое in ASSETS.glob("*"):
        старое.unlink()
    подписи = {
        "логотип_на_тёмном": "логотип-на-тёмном",
        "логотип_на_светлом": "логотип-на-светлом",
        "фото_автора": "фото",
    }
    for ключ, новое_имя in подписи.items():
        путь = (профиль.get("активы") or {}).get(ключ)
        if not путь:
            continue
        источник = PROFILES / имя / путь
        if not источник.exists():
            источник = Path(путь).expanduser()
        if not источник.exists():
            предупреждения.append(f"{ключ}: файл «{путь}» не найден — блок соберётся без него")
            continue
        shutil.copy2(источник, ASSETS / (новое_имя + источник.suffix))

    # Круглый кадр для страницы «Об авторе» лежал в этой же папке и только что был
    # стёрт вместе с активами прошлого профиля. Пересобираем сразу: иначе человек
    # правит цвет в профиле, а фото автора молча пропадает из готового документа.
    if any(ASSETS.glob("фото.*")):
        готово = subprocess.run(
            [sys.executable, str(ROOT / "scripts" / "prep_photo.py")],
            cwd=ROOT, capture_output=True, text=True,
        )
        if готово.returncode != 0:
            предупреждения.append(
                "круглое фото для страницы «Об авторе» пересобрать не вышло — "
                "запустите вручную: .venv/bin/python scripts/prep_photo.py"
            )
    return предупреждения


def main():
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--список" in sys.argv or "--list" in sys.argv:
        имена = список_профилей()
        print("Профили: " + (", ".join(имена) if имена else "— ни одного"))
        if ACTIVE_FILE.exists():
            print("Активный: " + ACTIVE_FILE.read_text(encoding="utf-8").strip())
        return

    имя = активный_профиль(аргументы[0] if аргументы else None)
    профиль = прочитать(имя)
    предупреждения = собрать_тему(профиль)
    предупреждения += собрать_автора(профиль)
    предупреждения += скопировать_активы(имя, профиль)
    if not имя.startswith("_"):
        ACTIVE_FILE.write_text(имя + "\n", encoding="utf-8")

    print(f"✅ Профиль «{имя}» запечён:")
    print("   context/theme.css — цвета и шрифты документа")
    print("   context/автор.md  — данные для страницы «Об авторе»")
    print("   assets/профиль/   — логотипы и фото")
    for п in предупреждения:
        print("   ⚠️  " + п)


if __name__ == "__main__":
    main()
