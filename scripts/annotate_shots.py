"""Номерные рамки «куда жать» и замазка личного — на ваших скриншотах.

Координаты задаются в долях (0..1) от размера картинки, поэтому не зависят от разрешения
экрана. Снять их помогает `scripts/make_grid.py` — он рисует поверх скрина сетку в долях.

Цвета берутся из активного профиля: рамки — цветом акцента, замазка — тёмным фоном.

Как пользоваться:

1) Разметка одной картинки прямо в команде:
   .venv/bin/python scripts/annotate_shots.py input/шаги/01.png \\
       --рамка 1 0.12,0.30,0.36,0.36 "Кнопка «Войти»" \\
       --замазать 0.60,0.05,1.00,0.09 "почта"

2) Пачкой по спеке (обычный JSON, его удобно писать нейросети):
   .venv/bin/python scripts/annotate_shots.py --спека ingest/рамки.json

   Формат спеки:
   [
     {"файл": "input/шаги/01.png",
      "рамки":   [{"номер": 1, "область": [0.12,0.30,0.36,0.36], "подпись": "Кнопка «Войти»"}],
      "замазать":[{"область": [0.60,0.05,1.00,0.09], "подпись": "почта"}]}
   ]

Выход: assets/shots-размеченные/<имя>.png
"""
import argparse
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
ВЫХОД = ROOT / "assets" / "shots-размеченные"
ЗАПАСНЫЕ_ЦВЕТА = {"акцент": (139, 21, 38), "тёплый": (201, 162, 39), "тёмный": (26, 29, 34)}


def стоп(текст):
    print("\n⛔ " + текст + "\n")
    sys.exit(1)


def в_кортеж(hex_цвет, запасной):
    h = (hex_цвет or "").strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    try:
        return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))
    except ValueError:
        return запасной


def цвета_профиля():
    """Акцент и тёплый — из активного профиля; нет профиля — работаем на запасных."""
    активный = ROOT / "профили" / "_активный"
    имя = активный.read_text(encoding="utf-8").strip() if активный.exists() else None
    файл = ROOT / "профили" / (имя or "") / "profile.json"
    if not файл.exists():
        return ЗАПАСНЫЕ_ЦВЕТА
    палитра = json.loads(файл.read_text(encoding="utf-8")).get("палитра", {})
    return {
        "акцент": в_кортеж(палитра.get("акцент"), ЗАПАСНЫЕ_ЦВЕТА["акцент"]),
        "тёплый": в_кортеж(палитра.get("тёплый"), ЗАПАСНЫЕ_ЦВЕТА["тёплый"]),
        "тёмный": в_кортеж(палитра.get("тёмный_фон_1"), ЗАПАСНЫЕ_ЦВЕТА["тёмный"]),
    }


def шрифт(размер):
    for путь in (
        ROOT / "assets" / "fonts" / "Montserrat.ttf",
        ROOT / "assets" / "fonts" / "OpenSans.ttf",
        Path("/System/Library/Fonts/Supplemental/Arial Bold.ttf"),
        Path("C:/Windows/Fonts/arialbd.ttf"),
    ):
        if путь.exists():
            try:
                return ImageFont.truetype(str(путь), размер)
            except Exception:
                pass
    return ImageFont.load_default()


def в_пиксели(картинка, область):
    W, H = картинка.size
    x0, y0, x1, y1 = область
    return [int(x0 * W), int(y0 * H), int(x1 * W), int(y1 * H)]


def замазать(рисунок, картинка, область, подпись, ц):
    x0, y0, x1, y1 = в_пиксели(картинка, область)
    ш, в = x1 - x0, y1 - y0
    рисунок.rounded_rectangle(
        [x0, y0, x1, y1], radius=max(6, в // 6), fill=ц["тёмный"], outline=ц["тёплый"],
        width=max(2, в // 28),
    )
    if подпись:
        размер = max(12, в // 3)
        ф = шрифт(размер)
        while размер > 11:
            рамка = рисунок.textbbox((0, 0), подпись, font=ф)
            if (рамка[2] - рамка[0]) <= ш - 18 and (рамка[3] - рамка[1]) <= в - 8:
                break
            размер -= 2
            ф = шрифт(размер)
        рамка = рисунок.textbbox((0, 0), подпись, font=ф)
        рисунок.text(
            (x0 + (ш - (рамка[2] - рамка[0])) / 2, y0 + (в - (рамка[3] - рамка[1])) / 2 - рамка[1]),
            подпись, fill=(235, 235, 235), font=ф,
        )


def рамка_с_номером(рисунок, картинка, область, номер, подпись, ц):
    x0, y0, x1, y1 = в_пиксели(картинка, область)
    W, H = картинка.size
    толщина = max(3, int(W * 0.0028))
    рисунок.rounded_rectangle(
        [x0, y0, x1, y1], radius=max(8, толщина * 3), outline=ц["акцент"], width=толщина
    )
    радиус = max(16, int(W * 0.014))
    рисунок.ellipse(
        [x0 - радиус, y0 - радиус, x0 + радиус, y0 + радиус],
        fill=ц["акцент"], outline=(255, 255, 255), width=max(2, толщина // 2),
    )
    ф = шрифт(int(радиус * 1.2))
    текст = str(номер)
    гр = рисунок.textbbox((0, 0), текст, font=ф)
    рисунок.text(
        (x0 - (гр[2] - гр[0]) / 2, y0 - (гр[3] - гр[1]) / 2 - гр[1]), текст, fill=(255, 255, 255), font=ф
    )
    if подпись:
        ф2 = шрифт(max(13, int(W * 0.012)))
        низ = y1 + max(4, int(H * 0.006))
        гр = рисунок.textbbox((0, 0), подпись, font=ф2)
        рисунок.rectangle(
            [x0, низ, x0 + (гр[2] - гр[0]) + 12, низ + (гр[3] - гр[1]) + 10], fill=ц["акцент"]
        )
        рисунок.text((x0 + 6, низ + 4), подпись, fill=(255, 255, 255), font=ф2)


def обработать(задание, ц):
    источник = Path(задание["файл"]).expanduser()
    if not источник.exists():
        print(f"  ⚠️  нет файла {источник} — пропускаю")
        return None
    картинка = Image.open(источник).convert("RGB")
    рисунок = ImageDraw.Draw(картинка)
    for з in задание.get("замазать", []):
        замазать(рисунок, картинка, з["область"], з.get("подпись", "• • •"), ц)
    for р in задание.get("рамки", []):
        рамка_с_номером(рисунок, картинка, р["область"], р["номер"], р.get("подпись"), ц)
    ВЫХОД.mkdir(parents=True, exist_ok=True)
    путь = ВЫХОД / (источник.stem + ".png")
    картинка.save(путь)
    print(f"  ✓ {путь.relative_to(ROOT)}  ({картинка.size[0]}×{картинка.size[1]})")
    return путь


def разобрать_область(строка):
    части = [float(ч) for ч in строка.replace(" ", "").split(",")]
    if len(части) != 4 or not all(0 <= ч <= 1 for ч in части):
        стоп(
            f"Область «{строка}» задана неверно. Нужны четыре числа от 0 до 1: "
            "лево,верх,право,низ — доли от размера картинки.\n"
            "   Снять их проще всего по сетке: .venv/bin/python scripts/make_grid.py <картинка>"
        )
    return части


def main():
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("файл", nargs="?", help="скриншот, который размечаем")
    ap.add_argument("--рамка", nargs=3, action="append", metavar=("НОМЕР", "ОБЛАСТЬ", "ПОДПИСЬ"),
                    default=[], help="номерная рамка «куда жать»")
    ap.add_argument("--замазать", nargs=2, action="append", metavar=("ОБЛАСТЬ", "ПОДПИСЬ"),
                    default=[], help="закрыть личное: почту, ключи, чужие имена")
    ap.add_argument("--спека", help="JSON со списком картинок и разметкой")
    args = ap.parse_args()

    ц = цвета_профиля()

    if args.спека:
        путь = Path(args.спека).expanduser()
        if not путь.exists():
            стоп(f"Спеки «{путь}» нет.")
        задания = json.loads(путь.read_text(encoding="utf-8"))
    elif args.файл:
        задания = [
            {
                "файл": args.файл,
                "рамки": [
                    {"номер": int(н), "область": разобрать_область(о), "подпись": п or None}
                    for н, о, п in args.рамка
                ],
                "замазать": [
                    {"область": разобрать_область(о), "подпись": п} for о, п in args.замазать
                ],
            }
        ]
    else:
        стоп("Не сказано, что размечать. Дайте картинку или спеку: --спека ingest/рамки.json")

    print(f"→ размечаю картинок: {len(задания)}")
    сделано = [обработать(з, ц) for з in задания]
    готовых = len([с for с in сделано if с])
    print(f"\n✅ Готово: {готовых} из {len(задания)} — в {ВЫХОД.relative_to(ROOT)}/")
    if готовых:
        print("   Проверьте глазами, что рамки легли на кнопки: на мелких элементах"
              "\n   ошибка в пару процентов уже уводит рамку мимо.")


if __name__ == "__main__":
    main()
