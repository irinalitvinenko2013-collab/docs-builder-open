"""Скринкаст → шаги инструкции: кадры берутся по смыслу, а не каждые N секунд.

Идея: человек записал экран и вслух говорил, что делает. Значит момент «а теперь нажимаем
сюда» уже отмечен голосом — надо взять кадр той самой секунды. Плюс отдельно ловим заметные
смены экрана: открылось новое окно, сменилась страница.

Вход:  видео записи экрана (mp4, mov, mkv…) + расшифровка из scripts/transcribe.py
       (если расшифровки ещё нет — сделайте её первой, иначе шаги будут только по смене экрана)
Выход: assets/shots-<слаг>/NN-<таймкод>.jpg — кадры
       ingest/<слаг>-шаги.json  — шаги: номер, время, что говорил человек, файл кадра
       ingest/<слаг>-шаги.md    — то же по-человечески, для вёрстки

Запуск:
    .venv/bin/python scripts/screencast_steps.py input/экран.mov
    .venv/bin/python scripts/screencast_steps.py input/экран.mov --слаг установка --макс-шагов 25
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INGEST = ROOT / "ingest"

# Слова, которыми человек показывает на экран. Нашли такое — берём кадр этой секунды.
УКАЗАТЕЛИ = [
    "нажим", "жму", "жмём", "жмем", "кликаю", "кликаем", "щёлк", "щелк",
    "открыв", "открою", "открываем", "захожу", "заходим", "переходим", "перехожу",
    "выбира", "выберу", "ставлю", "ставим", "включаю", "включаем", "выключаю",
    "ввожу", "вводим", "пишу", "пишем", "копирую", "копируем", "вставляю", "вставляем",
    "сюда", "вот здесь", "вот сюда", "вот тут", "видите", "смотрите",
    "сохраня", "загружа", "скачива", "удаля", "закрыва",
]
ЗАДЕРЖКА = 0.9  # сколько секунд ждать после фразы: сначала говорят, потом делают
ОТСТУП_ДО_СМЕНЫ = 0.4  # насколько раньше смены экрана снимать кадр, чтобы не поймать следующий


def стоп(текст):
    print("\n⛔ " + текст + "\n")
    sys.exit(1)


def таймкод(секунды):
    м, с = divmod(int(секунды), 60)
    ч, м = divmod(м, 60)
    return f"{ч:d}-{м:02d}-{с:02d}" if ч else f"{м:02d}-{с:02d}"


def человеческий_таймкод(секунды):
    м, с = divmod(int(секунды), 60)
    ч, м = divmod(м, 60)
    return f"{ч}:{м:02d}:{с:02d}" if ч else f"{м}:{с:02d}"


def найти_расшифровку(источник, слаг):
    for кандидат in (
        INGEST / f"{источник.stem}-расшифровка.json",
        INGEST / f"{слаг}-расшифровка.json",
    ):
        if кандидат.exists():
            return json.loads(кандидат.read_text(encoding="utf-8"))["куски"]
    return []


def моменты_по_речи(куски, длительность, смены=()):
    """Каждая фраза-указатель даёт один момент: время + что было сказано.

    Кадр берётся ПОСЛЕ фразы (сначала говорят, потом делают), но не дальше
    ближайшей смены экрана: иначе у шага «открываем настройки» окажется картинка
    уже следующего окна. Подпись про одно, картинка про другое — в инструкции это
    хуже, чем отсутствие картинки.
    """
    моменты = []
    for к in куски:
        текст = к["text"].strip()
        низ = текст.lower()
        if not any(у in низ for у in УКАЗАТЕЛИ):
            continue
        время = min(к["end"] + ЗАДЕРЖКА, (длительность or к["end"]) - 0.1)
        следующая = next((с for с in sorted(смены) if с > к["end"]), None)
        if следующая is not None and следующая <= время:
            # пауза после фразы упирается в смену экрана: кадр берём до неё,
            # но не раньше, чем человек договорил
            время = max(к["end"], следующая - ОТСТУП_ДО_СМЕНЫ)
        моменты.append({"время": max(время, 0), "фраза": текст, "откуда": "речь"})
    return моменты


ЗАМЕТНАЯ_РАЗНИЦА = 24    # на сколько уровней (из 255) должен измениться пиксель, чтобы считаться другим
ДОЛЯ_ЭКРАНА = 0.06       # какая доля таких пикселей означает, что экран сменился


def моменты_по_смене_экрана(кадры_и_время, порог=ДОЛЯ_ЭКРАНА):
    """Заметная смена картинки — тоже шаг: открылось окно, сменилась страница.

    Считаем ДОЛЮ изменившихся пикселей по цвету, а не среднюю разницу яркости:
    средняя разница размазывается по всему кадру и на настоящей смене страницы даёт
    сотые доли — порог по ней недостижим, детектор молчит всегда. Доля же разделяет
    чисто: покой — ноль, смена экрана — заметный процент. Курсор и мигающий курсор
    ввода задевают единицы пикселей и порога не берут.
    """
    моменты, прошлый = [], None
    for время, миниатюра in кадры_и_время:
        if прошлый is not None:
            пикселей = len(миниатюра) // 3
            изменились = sum(
                1
                for p in range(пикселей)
                if max(abs(миниатюра[p * 3 + k] - прошлый[p * 3 + k]) for k in range(3))
                > ЗАМЕТНАЯ_РАЗНИЦА
            )
            if пикселей and изменились / пикселей > порог:
                моменты.append({"время": время, "фраза": "", "откуда": "смена экрана"})
        прошлый = миниатюра
    return моменты


def проредить(моменты, минимум_секунд=2.5, максимум=None):
    """Убрать моменты, стоящие вплотную: у речи приоритет над сменой экрана."""
    моменты = sorted(моменты, key=lambda м: м["время"])
    отобранные = []
    for м in моменты:
        if отобранные and м["время"] - отобранные[-1]["время"] < минимум_секунд:
            if м["откуда"] == "речь" and отобранные[-1]["откуда"] != "речь":
                отобранные[-1] = м
            continue
        отобранные.append(м)
    if максимум and len(отобранные) > максимум:
        речевые = [м for м in отобранные if м["откуда"] == "речь"]
        отобранные = (речевые if len(речевые) >= максимум else отобранные)[:максимум]
    return отобранные


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("файл", help="видео записи экрана")
    ap.add_argument("--слаг", default=None, help="короткое имя работы")
    ap.add_argument("--макс-шагов", type=int, default=40, dest="макс")
    ap.add_argument("--ширина", type=int, default=1600, help="ширина кадра в пикселях")
    args = ap.parse_args()

    источник = Path(args.файл).expanduser()
    if not источник.exists():
        стоп(f"Файла «{источник}» нет. Положите запись в папку input/ и проверьте имя.")

    слаг = args.слаг or re.sub(r"[^\w\-]+", "-", источник.stem, flags=re.UNICODE).strip("-")

    try:
        import av
        from PIL import Image
    except ImportError:
        стоп("Не хватает библиотек для работы с видео. Один раз выполните: bash scripts/setup.sh")

    контейнер = av.open(str(источник))
    поток = контейнер.streams.video[0]
    поток.thread_type = "AUTO"
    длительность = float(контейнер.duration / av.time_base) if контейнер.duration else None

    print(f"→ смотрю запись: {источник.name}" + (f" ({человеческий_таймкод(длительность)})" if длительность else ""))

    # 1. миниатюры раз в секунду (в цвете — по яркости смены страниц не видно)
    миниатюры, прошлая_секунда = [], -1
    for кадр in контейнер.decode(video=0):
        если_время = float(кадр.pts * поток.time_base) if кадр.pts is not None else None
        if если_время is None:
            continue
        секунда = int(если_время)
        if секунда == прошлая_секунда:
            continue
        прошлая_секунда = секунда
        мини = кадр.to_image().convert("RGB").resize((32, 18))
        миниатюры.append((если_время, list(мини.tobytes())))
    if not миниатюры:
        стоп("Не получилось прочитать видео. Проверьте, открывается ли файл обычным плеером.")
    длительность = длительность or миниатюры[-1][0]

    # 2. моменты: сначала речь, потом смены экрана
    куски = найти_расшифровку(источник, слаг)
    if not куски:
        print("  ⚠️  расшифровки нет — шаги будут только по сменам экрана, без подписей.")
        print("     Сделайте её первой: .venv/bin/python scripts/transcribe.py " + str(источник))
    смены = [м["время"] for м in моменты_по_смене_экрана(миниатюры)]
    моменты = моменты_по_речи(куски, длительность, смены) + [
        {"время": t, "фраза": "", "откуда": "смена экрана"} for t in смены
    ]
    моменты = проредить(моменты, максимум=args.макс)
    if not моменты:
        стоп("Не нашла ни одного шага: экран не менялся и указаний в речи нет.")

    # 3. вытащить кадры этих секунд
    папка = ROOT / "assets" / f"shots-{слаг}"
    папка.mkdir(parents=True, exist_ok=True)
    for старый in папка.glob("*.jpg"):
        старый.unlink()

    контейнер = av.open(str(источник))
    поток = контейнер.streams.video[0]
    поток.thread_type = "AUTO"
    шаги, индекс = [], 0
    for кадр in контейнер.decode(video=0):
        if индекс >= len(моменты):
            break
        если_время = float(кадр.pts * поток.time_base) if кадр.pts is not None else None
        if если_время is None or если_время < моменты[индекс]["время"]:
            continue
        м = моменты[индекс]
        картинка = кадр.to_image()
        if картинка.width > args.ширина:
            высота = round(картинка.height * args.ширина / картинка.width)
            картинка = картинка.resize((args.ширина, высота), Image.LANCZOS)
        имя = f"{индекс + 1:02d}-{таймкод(м['время'])}.jpg"
        картинка.save(папка / имя, quality=88, optimize=True)
        шаги.append(
            {
                "шаг": индекс + 1,
                "время": round(м["время"], 2),
                "таймкод": человеческий_таймкод(м["время"]),
                "сказано": м["фраза"],
                "откуда": м["откуда"],
                "кадр": str((папка / имя).relative_to(ROOT)),
            }
        )
        индекс += 1

    INGEST.mkdir(exist_ok=True)
    (INGEST / f"{слаг}-шаги.json").write_text(
        json.dumps({"запись": источник.name, "шаги": шаги}, ensure_ascii=False, indent=1),
        encoding="utf-8",
    )
    строки = [
        f"# Шаги из записи экрана: {источник.name}",
        "",
        "> Кадры сняты автоматически: на фразах-указателях («нажимаю», «открываю») и на сменах",
        "> экрана. Курсор на кадре виден — он и показывает, куда нажимали. Рамки, если их ставить,",
        "> лягут по области, а не пиксель в пиксель: это честная граница такого способа.",
        "",
    ]
    for ш in шаги:
        строки.append(f"## Шаг {ш['шаг']} · {ш['таймкод']}")
        строки.append("")
        строки.append(ш["сказано"] or "_(здесь человек молчал — подпись нужно добавить словами)_")
        строки.append("")
        строки.append(f"![Шаг {ш['шаг']}]({ш['кадр']})")
        строки.append("")
    (INGEST / f"{слаг}-шаги.md").write_text("\n".join(строки), encoding="utf-8")

    по_речи = sum(1 for ш in шаги if ш["откуда"] == "речь")
    print(f"\n✅ Готово. Шагов: {len(шаги)} (по речи — {по_речи}, по смене экрана — {len(шаги) - по_речи})")
    print(f"   Кадры:  {папка.relative_to(ROOT)}/")
    print(f"   Шаги:   ingest/{слаг}-шаги.md")
    if по_речи < len(шаги) / 2:
        print("   ⚠️  Много шагов без подписи: человек говорил редко. Подписи можно добавить словами.")


if __name__ == "__main__":
    main()
